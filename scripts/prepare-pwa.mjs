import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
const template = readFileSync('src/pwa/service-worker.js', 'utf8');
const hash = createHash('sha256').update(template);
for (const file of ['offline.html','offline.css','offline.js','icon.svg','icon-192.png','icon-512.png','manifest.webmanifest']) hash.update(readFileSync(`public/${file}`));
const revision = hash.digest('hex').slice(0,16);
writeFileSync('public/sw.js', `// Automatically generated by scripts/prepare-pwa.mjs.\n${template.replaceAll('__CACHE_VERSION__',revision)}`);
console.log(`Prepared offline worker ${revision}`);
